CREATE DATABASE IF NOT EXISTS KIM_DB;
CREATE SCHEMA IF NOT EXISTS KIM_DB.PUBLIC;
USE DATABASE KIM_DB;
USE SCHEMA PUBLIC;

CREATE TABLE IF NOT EXISTS ACTIVITIES (
  ID VARCHAR(40) PRIMARY KEY, NAME VARCHAR(200) NOT NULL, CATEGORY VARCHAR(80),
  ELIGIBILITY VARCHAR(200), DESCRIPTION VARCHAR(2000), PLACES NUMBER(8,0) DEFAULT 0,
  ACTIVE BOOLEAN DEFAULT TRUE, UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS ROOMS (
  ID VARCHAR(40) PRIMARY KEY, NAME VARCHAR(200) NOT NULL, CAPACITY NUMBER(8,0),
  EQUIPMENT VARCHAR(1000), ACTIVE BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS REQUESTS (
  ID VARCHAR(40) PRIMARY KEY, TYPE VARCHAR(30) NOT NULL, PAYLOAD VARIANT NOT NULL,
  STATUS VARCHAR(30) DEFAULT 'PENDING', ADMIN_NOTE VARCHAR(2000),
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS MESSAGES (
  ID VARCHAR(40) DEFAULT UUID_STRING(), SESSION_ID VARCHAR(100), ROLE VARCHAR(20),
  CONTENT VARCHAR(10000), CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

MERGE INTO ACTIVITIES t USING (SELECT * FROM VALUES
('ACT-01','Taekwondo débutant','Sport','8–14 ans · débutant','Initiation aux techniques fondamentales du taekwondo.',4),
('ACT-02','Atelier Python','Numérique','15 ans et +','Découvrir la programmation avec Python.',18),
('ACT-03','Initiation au design numérique','Numérique','Tout public','Créer une première interface et comprendre les bases UX.',12),
('ACT-04','Club de lecture coréenne','Culture','Tout public','Découverte de la langue et de la culture coréennes.',10),
('ACT-05','Danse traditionnelle','Culture','Tout public','Atelier de découverte des danses traditionnelles.',14),
('ACT-06','Échecs & stratégie','Sport & loisirs','Tout public','Initiation et pratique des échecs.',16)
) s(ID,NAME,CATEGORY,ELIGIBILITY,DESCRIPTION,PLACES) ON t.ID=s.ID
WHEN NOT MATCHED THEN INSERT(ID,NAME,CATEGORY,ELIGIBILITY,DESCRIPTION,PLACES) VALUES(s.ID,s.NAME,s.CATEGORY,s.ELIGIBILITY,s.DESCRIPTION,s.PLACES);
